package com.example.agendavalenciana.ios

private var asserts = 0
private fun ok(value: Boolean, description: String) { check(value) { "PAS42 fallada: $description" }; asserts++ }
fun main() {
    val policy = IosSellerLegalPolicy
    val accepted = IosSellerCompany(11, "Cooperativa", true)
    val outdated = IosSellerCompany(12, "Associacio", false)
    val valid = IosSellerStatus(true, true, "https://agendaval.com/privacitat", "https://agendaval.com/condicions", listOf(accepted, outdated))
    val base = IosSellerActivation(99, 11, acceptedPrivacy=true, acceptedSales=true)
    val new = IosSellerActivation(99, kind="PERSON", displayName="Artista", taxId="12345678Z",
        address="Carrer Major 1", postalCode="46500", town="Sagunt",
        acceptedPrivacy=true, acceptedSales=true, privacyViewed=true, salesViewed=true)
    ok(policy.validLegalUrl(valid.privacyUrl), "https valid")
    ok(policy.validLegalUrl("https://legal.example.org/path?a=3"), "https query")
    ok(!policy.validLegalUrl("http://example.com"), "http blocked")
    ok(!policy.validLegalUrl("javascript://example.com"), "script blocked")
    ok(!policy.validLegalUrl("https://login@evil.com/docs"), "userinfo blocked")
    ok(!policy.validLegalUrl("https://notdomain/legal"), "host blocked")
    ok(!policy.validLegalUrl("https://example.com/abc x"), "spaces blocked")
    ok(!policy.validLegalUrl(" https://example.com/doc"), "whitespace prefix")
    ok(!policy.validLegalUrl("https://example.com/\nxxx"), "newline blocked")
    ok(policy.policiesUsable(valid), "policies present")
    ok(!policy.policiesUsable(valid.copy(policiesReady=false)), "policies unpublished")
    ok(!policy.policiesUsable(valid.copy(privacyUrl="")), "missing privacy")
    ok(!policy.policiesUsable(valid.copy(salesTermsUrl="http://unsafe.test")), "insecure terms")
    ok(policy.selectedCompany(valid, 11) == accepted, "existing company found")
    ok(policy.selectedCompany(valid, 12) == outdated, "other company found")
    ok(policy.selectedCompany(valid, 0) == null, "new company")
    ok(policy.selectedCompany(valid, 13) == null, "forged company")
    ok(policy.canSubmit(base, valid, true, setOf(99)), "previously accepted can proceed")
    ok(!policy.canSubmit(base, valid, false, setOf(99)), "registered required")
    ok(!policy.canSubmit(base, valid, true, setOf(98)), "ownership required")
    ok(!policy.canSubmit(base.copy(eventId=100), valid, true, setOf(99)), "other event blocked")
    ok(!policy.canSubmit(base.copy(existingCompanyId=15), valid, true, setOf(99)), "company injected")
    ok(!policy.canSubmit(base, valid.copy(policiesReady=false), true, setOf(99)), "legality unavailable")
    ok(!policy.canSubmit(base.copy(existingCompanyId=12), valid, true, setOf(99)), "outdated company cannot silently reuse")
    ok(policy.canSubmit(base.copy(existingCompanyId=12,privacyViewed=true,salesViewed=true), valid,true,setOf(99)), "updated notices")
    ok(!policy.canSubmit(new.copy(privacyViewed=false), valid, true, setOf(99)), "must open privacy")
    ok(!policy.canSubmit(new.copy(salesViewed=false), valid, true, setOf(99)), "must open sales")
    ok(!policy.canSubmit(new.copy(acceptedSales=false), valid, true, setOf(99)), "must consent")
    ok(policy.canSubmit(new, valid, true, setOf(99)), "new legal owner")
    ok(!policy.canSubmit(new.copy(postalCode="465"), valid, true, setOf(99)), "postal validation")
    ok(!policy.canSubmit(new.copy(taxId="short"), valid, true, setOf(99)), "tax validation")
    ok(!policy.canSubmit(new.copy(kind="OTHER"), valid, true, setOf(99)), "kind validation")
    ok(!policy.canSubmit(new.copy(eventId=0), valid, true, setOf(99)), "published required")
    ok(policy.postAcknowledged(99, 11, true, false, 99, 11), "post existing")
    ok(policy.postAcknowledged(99, 13, true, false, 99, 0), "post new")
    ok(!policy.postAcknowledged(98, 11, true, false, 99, 11), "wrong event")
    ok(!policy.postAcknowledged(99, 0, true, false, 99, 0), "invalid company")
    ok(!policy.postAcknowledged(99, 11, false, false, 99, 11), "not configured")
    ok(!policy.postAcknowledged(99, 11, true, true, 99, 11), "ticket unexpectedly enabled")
    ok(!policy.postAcknowledged(99, 11, true, false, 99, 12), "wrong existing company")
    ok(policy.getConfirmed(valid,11), "verified current owner")
    ok(!policy.getConfirmed(valid,12), "old terms not current")
    ok(!policy.getConfirmed(valid,14), "missing server owner")
    ok(!policy.getConfirmed(valid.copy(hasBilling=false),11), "no fiscal info")
    ok(!policy.getConfirmed(valid.copy(companies=emptyList()),11), "owner not found")
    val pendingSale = IosSellerSaleState(99,false,1,2)
    ok(IosSellerSalePolicy.canEnable(pendingSale,valid,setOf(99)), "can activate with fiscal, policy and active option")
    ok(!IosSellerSalePolicy.canEnable(pendingSale.copy(eventId=98),valid,setOf(99)), "not another event")
    ok(!IosSellerSalePolicy.canEnable(pendingSale.copy(activeOptions=0),valid,setOf(99)), "not without option")
    ok(!IosSellerSalePolicy.canEnable(pendingSale,valid.copy(hasBilling=false),setOf(99)), "not without billing")
    ok(!IosSellerSalePolicy.canEnable(pendingSale,valid.copy(policiesReady=false),setOf(99)), "not without legal notice")
    ok(!IosSellerSalePolicy.canEnable(pendingSale,valid.copy(companies=listOf(outdated)),setOf(99)), "not without current consents")
    ok(IosSellerSalePolicy.verified(99,true,pendingSale.copy(enabled=true)), "server confirms sale")
    ok(!IosSellerSalePolicy.verified(99,true,pendingSale), "no optimistic activation")
    ok(!IosSellerSalePolicy.verified(98,true,pendingSale.copy(enabled=true)), "sale belongs to wrong event")
    ok(IosSellerSalePolicy.verified(99,false,pendingSale), "verified disabled")
    println("PAS42_JVM_PASS assertions=$asserts")
}
