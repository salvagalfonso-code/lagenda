import com.example.agendavalenciana.ios.IosTicketOption
import com.example.agendavalenciana.ios.IosTicketCatalogPolicy as P

fun main() {
    var n = 0
    fun ok(condition: Boolean, label: String) { check(condition) { label }; n++ }
    val vip = IosTicketOption(1,"VIP",32.0,null,20,"2026-12-03","21:30",sector="VIP",offer="Anticipada",capacity=50,sold=20,reserved=5)
    val piste = IosTicketOption(2,"Pista",12.0,null,8,"2026-12-04","22:00",sector="Pista",capacity=100,sold=98,reserved=1)
    val free = IosTicketOption(3,"Gratuïta",0.0,null,6,"2026-12-04","19:00",sector="Pista",capacity=4,sold=4)
    val legacy = IosTicketOption(4,"General",10.0,null,6,"","",sector="")
    val old = IosTicketOption(5,"Passada",10.0,null,6,"2026-10-24","18:00")
    val inactive = IosTicketOption(6,"Inactiva",10.0,null,6,"2026-12-02","",active=false)
    val naN = IosTicketOption(7,"Preu invàlid",Double.NaN,null,6,"","")
    val invalidId = IosTicketOption(0,"",10.0,null,6,"","")
    val combined = listOf(vip,piste,free,legacy,old,inactive,naN,invalidId)
    ok(P.valid(vip),"VIP valid")
    ok(vip.available==25,"stock subtract sold reserved")
    ok(P.quantityLimit(vip)==6,"server purchase hard limit 6")
    ok(piste.available==1,"stock from capacity")
    ok(P.quantityLimit(piste)==1,"stock caps quantity")
    ok(free.soldOut,"sold out")
    ok(P.quantityLimit(free)==0,"sold out quantity zero")
    ok(!P.selectable(free),"sold out not selectable")
    ok(P.selectable(vip),"active stock selectable")
    ok(!P.selectable(inactive),"inactive unselectable")
    ok(!P.valid(naN),"NaN price rejected")
    ok(!P.valid(invalidId),"missing ID rejected")
    ok(P.quantityLimit(legacy)==6,"unlimited stock per order")
    ok(legacy.available==null,"unknown stock is not fabricated")
    val visible=P.visible(combined,"2026-11-01")
    ok(visible.map { it.id }.toSet()==setOf(1,2,3,4),"active, future, valid")
    ok(visible.first().id==4,"general admission first")
    ok(P.days(visible)==listOf("2026-12-03","2026-12-04"),"dates")
    ok(P.sectors(visible)==listOf("Pista","VIP"),"sectors")
    ok(P.filter(visible,"2026-12-03","VIP").map { it.id }==listOf(4,1),"general inclusions")
    ok(P.filter(visible,"2026-12-04","Pista").map { it.id }==listOf(4,3,2),"date+zone")
    ok("Zona: VIP" in P.details(vip) && "Anticipada" in P.details(vip),"labels")
    ok(!P.valid(vip.copy(maxPerOrder=21)),"20 max")
    ok(!P.valid(vip.copy(price=Double.NEGATIVE_INFINITY)),"infinite price")
    ok(!P.valid(vip.copy(price=-1.0)),"negative price")
    ok(P.visible(listOf(vip, vip.copy(name="duplicada"))).size==1,"deduplicate ID")
    ok(P.quantityLimit(null)==0,"unselected never purchasable")
    ok(P.quantityLimit(vip.copy(remaining=0,capacity=null))==0,"remaining fallback")
    ok(P.quantityLimit(vip.copy(capacity=0))==0,"capacity zero")
    println("PAS37_KOTLIN_JVM_PASS $n")
}
