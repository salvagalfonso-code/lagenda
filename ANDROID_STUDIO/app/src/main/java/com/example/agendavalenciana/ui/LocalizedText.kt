/** Idioma de la interfície. No altera l'idioma ni les dades dels esdeveniments. */
enum class UiLanguage(val code: String, val publicLabel: String) {
    VALENCIAN("ca", "Valencià"),
    SPANISH("es", "Castellano"),
    ENGLISH("en", "English");

    companion object {
        fun fromCode(code: String?): UiLanguage? = entries.firstOrNull { it.code == code }
    }
}

object UiLanguageStore {
    private const val PREFS = "agenda_ui_language"
    private const val KEY = "selected_language"

    fun read(context: Context): UiLanguage? =
        UiLanguage.fromCode(context.getSharedPreferences(PREFS, Context.MODE_PRIVATE).getString(KEY, null))

    fun save(context: Context, language: UiLanguage) {
        context.getSharedPreferences(PREFS, Context.MODE_PRIVATE)
            .edit()
            .putString(KEY, language.code)
            .apply()
        applyAndroidUiLocale(context, language)
    }
}

fun applyAndroidUiLocale(context: Context, language: UiLanguage) {
    val tag = when (language) {
        UiLanguage.VALENCIAN -> "ca-ES"
        UiLanguage.SPANISH -> "es-ES"
        UiLanguage.ENGLISH -> "en"
    }
    val locale = Locale.forLanguageTag(tag)
    Locale.setDefault(locale)
    val configuration = Configuration(context.resources.configuration).apply { setLocale(locale) }
    @Suppress("DEPRECATION")
    context.resources.updateConfiguration(configuration, context.resources.displayMetrics)
}

val LocalUiLanguage = compositionLocalOf { UiLanguage.VALENCIAN }
val LocalSetUiLanguage = staticCompositionLocalOf<(UiLanguage) -> Unit> { {} }

/**
 * Traducció només de textos de la interfície. Si el text no és una clau coneguda
 * (p. ex. títol d'un concert, nom d'artista o descripció editorial), es deixa intacte.
 */
fun translateUi(text: String, language: UiLanguage): String {
    if (language == UiLanguage.VALENCIAN || text.isBlank()) return text

    val es = spanishUi[text]
    val en = englishUi[text]
    val exact = if (language == UiLanguage.SPANISH) es else en
    if (exact != null) return exact

    // Frases de UI amb quantitats o noms variables. Sense regex per no penalitzar el feed.
    fun numericPrefix(suffix: String): String? =
        text.removeSuffix(suffix).takeIf { text.endsWith(suffix) && it.isNotBlank() && it.all(Char::isDigit) }

    numericPrefix(" sense llegir")?.let { value ->
        return if (language == UiLanguage.SPANISH) "$value sin leer" else "$value unread"
    }
    numericPrefix(" seguits")?.let { value ->
        return if (language == UiLanguage.SPANISH) "$value seguidos" else "$value followed"
    }
    numericPrefix(" poblacions preferides")?.let { value ->
        return if (language == UiLanguage.SPANISH) "$value poblaciones preferidas" else "$value preferred locations"
    }
    if (text.startsWith("Aforament total: ")) {
        val value = text.removePrefix("Aforament total: ")
        return if (language == UiLanguage.SPANISH) "Aforo total: $value" else "Total capacity: $value"
    }
    if (text.startsWith("Analítica de ")) {
        val value = text.removePrefix("Analítica de ")
        return if (language == UiLanguage.SPANISH) "Analítica de $value" else "Analytics for $value"
    }
    if (text.startsWith("Comandes · ")) {
        val value = text.removePrefix("Comandes · ")
        return if (language == UiLanguage.SPANISH) "Pedidos · $value" else "Orders · $value"
    }
    if (text.startsWith("Donacions · ")) {
        val value = text.removePrefix("Donacions · ")
        return if (language == UiLanguage.SPANISH) "Donaciones · $value" else "Donations · $value"
    }
    if (text.startsWith("Donació a ")) {
        val value = text.removePrefix("Donació a ")
        return if (language == UiLanguage.SPANISH) "Donación a $value" else "Donation to $value"
    }
    if (text.startsWith("Pujant i sincronitzant imatge: ") && text.endsWith("%")) {
        val value = text.removePrefix("Pujant i sincronitzant imatge: ").removeSuffix("%")
        return if (language == UiLanguage.SPANISH) "Subiendo y sincronizando imagen: $value%" else "Uploading and syncing image: $value%"
    }
    if (text.startsWith("Preu: ") && text.endsWith(" €.")) {
        val value = text.removePrefix("Preu: ").removeSuffix(" €.")
        return if (language == UiLanguage.SPANISH) "Precio: $value €." else "Price: €$value."
    }
    numericPrefix(" places disponibles")?.let { value ->
        return if (language == UiLanguage.SPANISH) "$value plazas disponibles" else "$value places available"
    }
    numericPrefix(" visualitzacions")?.let { value ->
        return if (language == UiLanguage.SPANISH) "$value visualizaciones" else "$value views"
    }
    if (text.startsWith("Entrada ")) {
        val value = text.removePrefix("Entrada ")
        if (value.all(Char::isDigit)) {
            return if (language == UiLanguage.SPANISH) "Entrada $value" else "Ticket $value"
        }
    }

    return text
}

@Composable
fun uiText(text: String): String = translateUi(text, LocalUiLanguage.current)

/**
 * Substitució compatible amb Material3 Text. Centralitza la traducció sense tocar
 * contingut cultural: només es tradueixen les claus conegudes de la interfície.
 */
@Composable
fun Text(
    text: String,
    modifier: Modifier = Modifier,
    color: Color = Color.Unspecified,
    fontSize: TextUnit = TextUnit.Unspecified,
    fontStyle: FontStyle? = null,
    fontWeight: FontWeight? = null,
    fontFamily: FontFamily? = null,
    letterSpacing: TextUnit = TextUnit.Unspecified,
    textDecoration: TextDecoration? = null,
    textAlign: TextAlign? = null,
    lineHeight: TextUnit = TextUnit.Unspecified,
    overflow: TextOverflow = TextOverflow.Clip,
    softWrap: Boolean = true,
    maxLines: Int = Int.MAX_VALUE,
    minLines: Int = 1,
    onTextLayout: ((TextLayoutResult) -> Unit)? = null,
    style: TextStyle = LocalTextStyle.current
) {
    MaterialText(
        text = uiText(text),
        modifier = modifier,
        color = color,
        fontSize = fontSize,
        fontStyle = fontStyle,
        fontWeight = fontWeight,
        fontFamily = fontFamily,
        letterSpacing = letterSpacing,
        textDecoration = textDecoration,
        textAlign = textAlign,
        lineHeight = lineHeight,
        overflow = overflow,
        softWrap = softWrap,
        maxLines = maxLines,
        minLines = minLines,
        onTextLayout = onTextLayout,
        style = style
    )
}

