package com.example.agendavalenciana.ios

fun main() {
    var total = 0
    fun c(value: Boolean) { check(value) { "Comprovació ${total+1} fallida" }; total++ }
    val empty = IosCampaignTarget()
    for (placement in listOf("HEADER", "FEED_NORMAL", "FEED_PREMIUM", "POPUP"))
        for (days in listOf(1, 3, 7)) c(IosAdvertisingPolicy.valid(IosCampaignDraft(7, placement, days)))
    for (placement in listOf("header", "INVALID", "", "POP-UP")) c(!IosAdvertisingPolicy.valid(IosCampaignDraft(7, placement, 1)))
    for (days in listOf(0, -1, 2, 5, 8, 30)) c(!IosAdvertisingPolicy.valid(IosCampaignDraft(7, "HEADER", days)))
    c(!IosAdvertisingPolicy.valid(IosCampaignDraft(0)))
    c(!IosAdvertisingPolicy.valid(IosCampaignDraft(-1)))
    c(!IosAdvertisingPolicy.valid(IosCampaignDraft(1, target=empty.copy(styles=setOf("")))))
    c(!IosAdvertisingPolicy.valid(IosCampaignDraft(1, target=empty.copy(terms=setOf("x".repeat(91))))))
    c(!IosAdvertisingPolicy.valid(IosCampaignDraft(1, target=empty.copy(towns=(1..31).map { "t$it" }.toSet()))))
    c(IosAdvertisingPolicy.valid(IosCampaignDraft(1, target=empty.copy(styles=setOf("rock", "teatre"), all=true))))
    val payment = IosCampaignPayment(35, "pi_hello_secret_abc", "pk_test_abc", 999, "eur", "Agenda", "test")
    c(IosAdvertisingPolicy.validPayment(payment))
    c(!IosAdvertisingPolicy.validPayment(payment.copy(adId=0)))
    c(!IosAdvertisingPolicy.validPayment(payment.copy(secret="fake")))
    c(!IosAdvertisingPolicy.validPayment(payment.copy(key="pk_unknown")))
    c(!IosAdvertisingPolicy.validPayment(payment.copy(cents=0)))
    c(!IosAdvertisingPolicy.validPayment(payment.copy(cents=-5)))
    c(!IosAdvertisingPolicy.validPayment(payment.copy(currency="usd")))
    c(!IosAdvertisingPolicy.validPayment(payment.copy(merchant="")))
    c(!IosAdvertisingPolicy.validPayment(payment.copy(mode="live")))
    c(IosAdvertisingPolicy.validPayment(payment.copy(mode="live",key="pk_live_xyz")))
    val live = IosCampaign(35, 7, "HEADER", "active", "2026-11-01", "2026-11-08", 999, target=empty)
    val status = IosCampaignStatus(35, "active", live)
    c(IosAdvertisingPolicy.activeConfirmed(35, status, listOf(live)))
    c(!IosAdvertisingPolicy.activeConfirmed(0, status, listOf(live)))
    c(!IosAdvertisingPolicy.activeConfirmed(36, status, listOf(live)))
    c(!IosAdvertisingPolicy.activeConfirmed(35, status.copy(adId=36), listOf(live)))
    c(!IosAdvertisingPolicy.activeConfirmed(35, status.copy(status="payment_pending"), listOf(live)))
    c(!IosAdvertisingPolicy.activeConfirmed(35, status.copy(ad=null), listOf(live)))
    c(!IosAdvertisingPolicy.activeConfirmed(35, status.copy(ad=live.copy(id=37)), listOf(live)))
    c(!IosAdvertisingPolicy.activeConfirmed(35, status.copy(ad=live.copy(status="pending")), listOf(live)))
    c(!IosAdvertisingPolicy.activeConfirmed(35, status, listOf(live.copy(status="pending"))))
    c(!IosAdvertisingPolicy.activeConfirmed(35, status, emptyList()))
    c(!IosAdvertisingPolicy.activeConfirmed(35, status, listOf(live, live)))
    c(IosAdvertisingPolicy.terminalFailure("payment_failed"))
    c(IosAdvertisingPolicy.terminalFailure("CANCELLED"))
    c(!IosAdvertisingPolicy.terminalFailure("payment_pending"))
    c(!IosAdvertisingPolicy.terminalFailure("active"))
    val changed = empty.copy(towns=setOf("Sagunt"), highIntent=true)
    c(IosAdvertisingPolicy.updatedTarget(live, changed, listOf(live.copy(target=changed))))
    c(!IosAdvertisingPolicy.updatedTarget(live, changed, listOf(live)))
    c(!IosAdvertisingPolicy.updatedTarget(live, changed, listOf(live.copy(eventId=5,target=changed))))
    c(!IosAdvertisingPolicy.updatedTarget(live, changed, listOf(live.copy(placement="POPUP",target=changed))))
    c(!IosAdvertisingPolicy.updatedTarget(live, changed, listOf(live.copy(target=changed),live.copy(target=changed))))
    c(IosAdvertisingPolicy.updatedVisual(35,.2f,.7f,false,listOf(live.copy(focusX=.2f,focusY=.7f))))
    c(!IosAdvertisingPolicy.updatedVisual(35,.2f,.7f,false,listOf(live)))
    c(!IosAdvertisingPolicy.updatedVisual(35,-.1f,.7f,false,listOf(live)))
    c(!IosAdvertisingPolicy.updatedVisual(35,.2f,1.1f,false,listOf(live)))
    c(IosAdvertisingPolicy.updatedVisual(35,.5f,.5f,true,listOf(live.copy(imageUrl=""))))
    c(!IosAdvertisingPolicy.updatedVisual(35,.5f,.5f,true,listOf(live.copy(imageUrl="https://example.com/image.jpg"))))
    c(IosAdvertisingPolicy.parseCsv(" música,  teatre ; dansa\npatrimoni") == setOf("música","teatre","dansa","patrimoni"))
    c(IosAdvertisingPolicy.parseCsv(",,;") .isEmpty())
    println("PAS 44 — $total assercions Kotlin/JVM correctes")
}
