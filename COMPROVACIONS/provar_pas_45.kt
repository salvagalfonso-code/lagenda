package com.example.agendavalenciana.ios

fun main() {
    var count = 0
    fun ok(value: Boolean, name: String) { check(value) { "PAS45 $name" }; count++ }
    val a = "Tres Fan Ball"
    val base = IosArtistProduct(21, a, "Disc", "DISC", "Àlbum", "https://example.org/disc.jpg", 1499, 450, 3, true)
    val good = IosStoreDraft(21, a, "Disc", "DISC", "Àlbum", "https://example.org/disc.jpg", 1499, 450, 3)
    ok(IosArtistStorePolicy.validArtist(a), "valid artist")
    ok(!IosArtistStorePolicy.validArtist(" "), "empty artist")
    ok(!IosArtistStorePolicy.validArtist("a".repeat(191)), "oversized artist")
    ok(IosArtistStorePolicy.validDraft(good), "valid draft")
    ok(!IosArtistStorePolicy.validDraft(good.copy(id=-1)), "negative id")
    ok(!IosArtistStorePolicy.validDraft(good.copy(artist="")), "no artist")
    ok(!IosArtistStorePolicy.validDraft(good.copy(name="")), "empty product")
    ok(!IosArtistStorePolicy.validDraft(good.copy(name="x".repeat(181))), "long name")
    ok(!IosArtistStorePolicy.validDraft(good.copy(type="FOOD")), "bad type")
    ok(IosArtistStorePolicy.validDraft(good.copy(type="MERCH")), "merch allowed")
    ok(!IosArtistStorePolicy.validDraft(good.copy(description="a".repeat(4001))), "long description")
    ok(!IosArtistStorePolicy.validDraft(good.copy(priceCents=-1)), "negative price")
    ok(!IosArtistStorePolicy.validDraft(good.copy(priceCents=100_000_000)), "huge price")
    ok(!IosArtistStorePolicy.validDraft(good.copy(shippingCents=-1)), "negative shipping")
    ok(!IosArtistStorePolicy.validDraft(good.copy(stock=-1)), "negative stock")
    ok(IosArtistStorePolicy.validDraft(good.copy(stock=null)), "unlimited stock")
    ok(!IosArtistStorePolicy.validDraft(good.copy(imageUrl="http://invalid")), "unsafe image URL")
    ok(!IosArtistStorePolicy.validDraft(good.copy(imageUrl="//example.org/x")), "protocol relative URL")
    ok(IosArtistStorePolicy.sameDraft(good, base), "exact product")
    ok(!IosArtistStorePolicy.sameDraft(good, base.copy(artist="Tres Fan Balls")), "artist collision")
    ok(!IosArtistStorePolicy.sameDraft(good, base.copy(priceCents=1200)), "price mismatch")
    ok(!IosArtistStorePolicy.sameDraft(good, base.copy(stock=8)), "stock mismatch")
    ok(!IosArtistStorePolicy.sameDraft(good, base.copy(active=false)), "inactive product")
    ok(IosArtistStorePolicy.saved(good, listOf(base.copy(name="Old")), listOf(base), 21), "update confirmed")
    ok(!IosArtistStorePolicy.saved(good, listOf(base), listOf(base.copy(name="Wrong")), 21), "false update")
    ok(!IosArtistStorePolicy.saved(good, emptyList(), listOf(base), 21), "new id differs from draft id")
    val fresh = good.copy(id=0)
    ok(IosArtistStorePolicy.saved(fresh, emptyList(), listOf(base),21), "new item confirmed")
    ok(!IosArtistStorePolicy.saved(fresh, emptyList(), listOf(base),22), "new id mismatched")
    ok(!IosArtistStorePolicy.saved(fresh, listOf(base), listOf(base),21), "old item not new")
    ok(!IosArtistStorePolicy.saved(fresh, emptyList(), listOf(base,base.copy(id=22)),0), "ambiguous duplicates")
    ok(IosArtistStorePolicy.deleted(21, listOf(base), emptyList()), "deleted confirmed")
    ok(!IosArtistStorePolicy.deleted(21, emptyList(), emptyList()), "cannot delete nonexistent")
    ok(!IosArtistStorePolicy.deleted(21, listOf(base), listOf(base)), "still on server")
    ok(IosArtistStorePolicy.canBuy(base,1), "can buy")
    ok(IosArtistStorePolicy.canBuy(base,3), "can buy available")
    ok(!IosArtistStorePolicy.canBuy(base,4), "stock exhausted")
    ok(!IosArtistStorePolicy.canBuy(base,0), "zero quantity")
    ok(!IosArtistStorePolicy.canBuy(base,21), "too many")
    ok(!IosArtistStorePolicy.canBuy(base.copy(active=false),1), "inactive cannot buy")
    ok(!IosArtistStorePolicy.canBuy(base.copy(stock=0),1), "zero stock")
    ok(IosArtistStorePolicy.canBuy(base.copy(stock=null),20), "unlimited")
    val addr = IosStoreAddress("Salvador", "Carrer de la Música, 2", "46001", "València", "Espanya")
    ok(IosArtistStorePolicy.validAddress(addr), "valid address")
    ok(!IosArtistStorePolicy.validAddress(addr.copy(recipient="")), "missing recipient")
    ok(!IosArtistStorePolicy.validAddress(addr.copy(street="A")), "invalid street")
    ok(!IosArtistStorePolicy.validAddress(addr.copy(postcode="")), "missing postcode")
    ok(!IosArtistStorePolicy.validAddress(addr.copy(city="")), "missing city")
    ok(!IosArtistStorePolicy.validAddress(addr.copy(country="")), "missing country")
    val p=IosStorePayment(12,21,5,"pi_123_secret_abc", "pk_test_ABC",2500,"eur","l'Agenda","test")
    ok(IosArtistStorePolicy.validPayment(p), "valid test payment")
    ok(IosArtistStorePolicy.validPayment(p.copy(mode="live", publicKey="pk_live_X")), "valid live")
    ok(!IosArtistStorePolicy.validPayment(p.copy(publicKey="pk_live_X")), "mode mismatch")
    ok(!IosArtistStorePolicy.validPayment(p.copy(orderId=0)), "invalid order")
    ok(!IosArtistStorePolicy.validPayment(p.copy(ownerId=0)), "invalid owner")
    ok(!IosArtistStorePolicy.validPayment(p.copy(productId=0)), "invalid product")
    ok(!IosArtistStorePolicy.validPayment(p.copy(amountCents=0)), "free Stripe intent")
    ok(!IosArtistStorePolicy.validPayment(p.copy(clientSecret="madeup")), "invalid secret")
    ok(!IosArtistStorePolicy.validPayment(p.copy(currency="usd")), "wrong currency")
    val receipt=IosStorePaidOrder(12,"paid","Disc",1,1499,450,2500)
    ok(IosArtistStorePolicy.paidConfirmed(p,receipt), "server paid")
    ok(!IosArtistStorePolicy.paidConfirmed(p,receipt.copy(id=13)), "wrong order")
    ok(!IosArtistStorePolicy.paidConfirmed(p,receipt.copy(status="pending")), "pending not paid")
    ok(!IosArtistStorePolicy.paidConfirmed(p,receipt.copy(status="failed")), "failed not paid")
    ok(!IosArtistStorePolicy.paidConfirmed(p,receipt.copy(quantity=0)), "invalid quantity")
    val order=IosStoreOrder(12,"Disc",1,2500,"paid","Pau","Carrer","46001","València","Espanya","2026-11-01")
    ok(IosArtistStorePolicy.confirmedShipped(12,listOf(order),listOf(order.copy(status="shipped"))), "shipping confirmed")
    ok(!IosArtistStorePolicy.confirmedShipped(12,listOf(order),listOf(order)), "shipping not confirmed")
    ok(!IosArtistStorePolicy.confirmedShipped(12,listOf(order),listOf(order.copy(status="refunded"))), "refunded not shipped")
    ok(!IosArtistStorePolicy.confirmedShipped(12,listOf(order.copy(status="shipped")),listOf(order.copy(status="shipped"))), "already shipped")
    println("PAS45_JVM_PASS $count comprovacions")
}
