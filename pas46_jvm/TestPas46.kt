package com.example.agendavalenciana.ios
fun main() {
    var n=0
    fun ok(v:Boolean) {check(v);n++}
    val c=IosDonationConfig(true,"Suport","","", listOf(500,1000,2000),100,100000)
    ok(IosSpecialCommercePolicy.validConfig(c))
    ok(!IosSpecialCommercePolicy.validConfig(c.copy(minCents=5000)))
    ok(IosSpecialCommercePolicy.validDonationAmount(c,100))
    ok(!IosSpecialCommercePolicy.validDonationAmount(c.copy(active=false),500))
    ok(!IosSpecialCommercePolicy.validDonationAmount(c,100001))
    val p=IosDonationPayment(5,16,"Grup",1000,"pi_abc_secret_xyz","pk_test_abc","l'Agenda","test")
    ok(IosSpecialCommercePolicy.validDonationPayment(p))
    ok(IosSpecialCommercePolicy.confirmedDonation(p,IosDonationReceipt(16,"paid",1000)))
    ok(!IosSpecialCommercePolicy.confirmedDonation(p,IosDonationReceipt(16,"pending",1000)))
    ok(!IosSpecialCommercePolicy.confirmedDonation(p,IosDonationReceipt(18,"paid",1000)))
    ok(!IosSpecialCommercePolicy.confirmedDonation(p,IosDonationReceipt(16,"paid",500)))
    ok(!IosSpecialCommercePolicy.validPayment("fake","pk_test_ok","test"))
    ok(!IosSpecialCommercePolicy.validPayment("pi_ok_secret_a","pk_test_ok","live"))
    val product=IosServiceProduct(6,2,"Sessió","","",300,true,5,true)
    val service=IosSpecialService(2,7,"Skate","","","#FFE082",true,listOf(product))
    ok(IosSpecialCommercePolicy.canBuy(service,product,1))
    ok(IosSpecialCommercePolicy.canBuy(service,product,5))
    ok(!IosSpecialCommercePolicy.canBuy(service,product,6))
    ok(!IosSpecialCommercePolicy.canBuy(service,product,0))
    ok(!IosSpecialCommercePolicy.canBuy(service.copy(active=false),product,1))
    ok(!IosSpecialCommercePolicy.canBuy(service,product.copy(active=false),1))
    ok(!IosSpecialCommercePolicy.canBuy(service,product.copy(serviceId=3),1))
    val pay=IosSpecialPayment(5,14,7,2,"pi_abc_secret_123","pk_test_123",600,"l'Agenda","test")
    ok(IosSpecialCommercePolicy.validSpecialPayment(pay))
    ok(IosSpecialCommercePolicy.confirmedService(pay,IosSpecialOrder(14,"paid","Skate",600,"qr_valid")))
    ok(!IosSpecialCommercePolicy.confirmedService(pay,IosSpecialOrder(14,"paid","Skate",600,"")))
    ok(!IosSpecialCommercePolicy.confirmedService(pay,IosSpecialOrder(14,"pending","Skate",600,"qr")))
    ok(!IosSpecialCommercePolicy.confirmedService(pay,IosSpecialOrder(14,"paid","Skate",900,"qr")))
    ok(!IosSpecialCommercePolicy.confirmedService(pay,IosSpecialOrder(15,"paid","Skate",600,"qr")))
    val before=listOf(service)
    ok(IosSpecialCommercePolicy.serviceSaved(7,before,listOf(service.copy(name="Skate 2")),2,"Skate 2","","","#FFE082"))
    ok(!IosSpecialCommercePolicy.serviceSaved(7,before,before,2,"Skate 2","","","#FFE082"))
    ok(IosSpecialCommercePolicy.productSaved(listOf(product),listOf(product.copy(priceCents=500)),product.copy(priceCents=500)))
    ok(!IosSpecialCommercePolicy.productSaved(listOf(product),listOf(product),product.copy(priceCents=500)))
    ok(IosSpecialCommercePolicy.redeemAllowed(IosSpecialInspection(4,7,"paid","Skate",300)))
    ok(!IosSpecialCommercePolicy.redeemAllowed(IosSpecialInspection(4,7,"redeemed","Skate",300)))
    ok(!IosSpecialCommercePolicy.redeemAllowed(IosSpecialInspection(0,7,"paid","Skate",300)))
    println("PASS: $n real Kotlin/JVM policy assertions")
}
